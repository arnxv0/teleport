"""Teleport dashboard server.

  python3 -m teleport.dashboard [--archil] [--port 8787]
    /     2D view: counters, workers, event log, review table with evidence
    /3d   3D control panel: machines, workers, and tasks teleporting between machines

Local mode reads the disk dir and kills/launches local processes. --archil reads the Archil disk
through its S3 object API and kills/launches sandboxes.
"""
import argparse
import json
import os
import secrets
import shlex
import subprocess
import sys
import threading
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

from . import config, view
from .swarm import get_backend

HERE = os.path.dirname(os.path.abspath(__file__))
JOIN_CODE = os.environ.get("TELEPORT_JOIN_CODE") or secrets.token_hex(3)

JOIN_SH = r"""#!/usr/bin/env bash
# Teleport: join this machine to a running swarm. Generated by the dashboard for run __RUN__.
# The code runs from the shared Archil disk itself, so nothing else needs installing.
set -euo pipefail
N="${1:-4}"
DISK_ID="__DISK_ID__"; DISK_NAME="__DISK_NAME__"; ORG="__ORG__"; REGION="__REGION__"
export ARCHIL_MOUNT_TOKEN="__TOKEN__"
HOST="$(hostname -s | tr '[:upper:]' '[:lower:]')"
if [ -n "${TELEPORT_ROOT:-}" ]; then
  MNT="$TELEPORT_ROOT"                                   # disk already mounted here
elif [ "$(uname)" = "Darwin" ]; then
  MNT="/Volumes/$DISK_NAME"
  if [ ! -f "$MNT/tasks/manifest.json" ]; then
    [ -x /usr/local/bin/archil-mount ] || { echo "Install the Archil client first: curl -s https://archil.com/install | sh"; exit 1; }
    sudo /usr/local/bin/archil-mount "archil://$REGION/$ORG/$DISK_NAME?token=$ARCHIL_MOUNT_TOKEN&shared=true" "$MNT"
  fi
else
  MNT="/mnt/$DISK_NAME"
  if [ ! -f "$MNT/tasks/manifest.json" ]; then
    command -v archil >/dev/null || { echo "Install the Archil client first: curl -s https://archil.com/install | sh"; exit 1; }
    sudo mkdir -p "$MNT"
    sudo --preserve-env=ARCHIL_MOUNT_TOKEN archil mount "$DISK_ID" "$MNT" --region "$REGION" --conditional
  fi
fi
[ -f "$MNT/tasks/manifest.json" ] || { echo "mount failed: $MNT has no tasks"; exit 1; }
cd "$MNT"
export TELEPORT_ROOT="$MNT" TELEPORT_MACHINE="byo:$HOST"
export OPENAI_API_KEY="${OPENAI_API_KEY:-__OPENAI__}" KEENABLE_API_KEY="${KEENABLE_API_KEY:-__KEENABLE__}"
export TELEPORT_STEP_DELAY="__DELAY__"
for i in $(seq 1 "$N"); do
  nohup python3 -m teleport.worker --id "byo-$HOST-$i" > "/tmp/teleport-byo-$i.out" 2>&1 &
  echo "started worker byo-$HOST-$i (pid $!)"
done
echo "Joined run __RUN__ with $N workers as machine byo:$HOST. Stop with: pkill -f teleport.worker"
"""

PAGES = {"/": "dashboard.html", "/index.html": "dashboard.html", "/3d": "dashboard3d.html",
         "/teleports": "teleports.html", "/connect": "connect.html",
         "/data": "data.html"}


class App:
    def __init__(self, backend_name):
        self.mode = backend_name
        self.run_file = os.path.join(config.REPO, f".teleport-current-{backend_name}.json")
        self.run = None
        self.backend = self._restore() or get_backend(backend_name)
        self._snap, self._tele = None, None
        self._attach(self.backend)
        threading.Thread(target=self._refresh_loop, daemon=True).start()

    def _restore(self):
        """Re-attach to the last run after a server restart."""
        try:
            with open(self.run_file) as f:
                saved = json.load(f)
        except (FileNotFoundError, json.JSONDecodeError):
            return None
        self.run = saved["run"]
        if self.mode == "archil":
            from .backends.archil import ArchilBackend
            return ArchilBackend(state_path=saved["where"])
        from .backends.local import LocalBackend
        return LocalBackend(root=saved["where"])

    def _save_run(self):
        where = self.backend.state_path if self.mode == "archil" else self.backend.root
        with open(self.run_file, "w") as f:
            json.dump({"run": self.run, "where": where}, f)

    def _refresh_loop(self):
        """Keep a warm snapshot so every page/tab load is instant (building it over the Archil S3 API
        takes 1-3s; doing that per request made each tab switch show 'Connecting')."""
        n = 0
        while True:
            try:
                self._snap = self.view.state()
                if n % 2 == 0:
                    self._tele = self.view.teleports()
            except Exception as e:
                print("refresh error", e, flush=True)
            n += 1
            time.sleep(1)

    def _attach(self, backend):
        self._snap, self._tele = None, None
        self.backend = backend
        reader = (view.ArchilReader(backend.s["disk_id"]) if self.mode == "archil"
                  else view.LocalReader(backend.root))
        self.view = view.View(reader)

    def teleports(self):
        return self._tele or self.view.teleports()

    def mark_accepted(self, ids):
        """Reflect accepts in the warm snapshot right away (the next refresh confirms from the disk)."""
        snap = self._snap
        if not snap:
            return
        for f in snap.get("fix_list", []):
            if f["fix_id"] in ids:
                f["accepted"] = True
        snap["accepted"] = sum(1 for f in snap.get("fix_list", []) if f.get("accepted"))

    def state(self):
        st = {**(self._snap or self.view.state()), "mode": self.mode, "run": self.run}
        if self.run and self.run["phase"] == "running" and st["total"] and st["done"] >= st["total"]:
            self.run.update(phase="complete", message=f"{st['done']} records verified; releasing sandboxes")
            self._save_run()
            if self.mode == "archil":
                threading.Thread(target=self._release, daemon=True).start()
        return st

    # ----- paste a URL -> planner agent -> ingest -> swarm -----
    def start(self, url, limit, workers):
        if self.run and self.run["phase"] in ("planning", "ingesting", "launching"):
            raise RuntimeError("a run is already starting")
        if not url.startswith(("https://", "http://", "s3://")):
            raise ValueError("URL must start with https://, http:// or s3://")
        rid = time.strftime("r%H%M%S")
        self.run = {"id": rid, "source_url": url, "phase": "planning", "limit": limit, "workers": workers,
                    "started_at": time.time(), "message": "creating a fresh disk"}
        threading.Thread(target=self._run, args=(rid, url, limit, workers), daemon=True).start()
        return rid

    def _phase(self, phase, message):
        self.run.update(phase=phase, message=message)
        try:
            self._save_run()
        except Exception:
            pass
        print(f"[run {self.run['id']}] {phase}: {message}", flush=True)

    def _run(self, rid, url, limit, workers):
        try:
            args = f"--url {shlex.quote(url)} --limit {int(limit)}"
            if self.mode == "archil":
                from .backends.archil import ArchilBackend
                b = ArchilBackend(state_path=os.path.join(config.REPO, f".teleport-{rid}.json"))
                b.setup(f"tp-{rid}")
                self._attach(b)
                self._phase("planning", "planner agent is reading sample rows (in an Archil sandbox)")
                ingest = threading.Thread(target=b.ingest, args=(args,), daemon=True)
            else:
                from .backends.local import LocalBackend
                b = LocalBackend(root=os.path.join(config.REPO, "runs", rid))
                self._attach(b)
                self._phase("planning", "planner agent is reading sample rows")
                env = {**os.environ, "TELEPORT_ROOT": b.root}
                ingest = threading.Thread(target=subprocess.run, daemon=True, kwargs={
                    "args": [sys.executable, "-m", "teleport.ingest", *shlex.split(args)],
                    "env": env, "cwd": config.REPO})
            ingest.start()
            while ingest.is_alive():  # follow progress by watching the disk
                if self.view._json("tasks/manifest.json"):
                    break
                if self.view._json("plan.json") and self.run["phase"] == "planning":
                    p = self.view._json("plan.json")
                    self._phase("ingesting", f"plan ready: verify {', '.join(c['field'] for c in p['checks'])}"
                                             f" for each {p['entity']}; loading rows")
                time.sleep(1)
            ingest.join()
            man = self.view._json("tasks/manifest.json")
            if not man:
                raise RuntimeError("ingest produced no tasks (unreadable URL or planner failure)")
            self._phase("launching", f"launching {workers} agents for {man['count']} records")
            if self.mode == "archil":
                # pools of up to 10 sandboxes (A, B, C, ...): each pool is one ring in Swarm 3D
                pools = [min(10, workers - i) for i in range(0, workers, 10)]
                if len(pools) == 1 and workers > 1:  # small swarms still get two pools to kill between
                    pools = [(workers + 1) // 2, workers // 2]
                for i, k in enumerate(pools):
                    b.launch(k, "ABCDEFGHIJ"[i])
            else:
                b.launch((workers + 1) // 2, "laptop-A")
                b.launch(workers // 2, "laptop-B")
            b.reaper()
            self._phase("running", f"{workers} agents cleaning {man['count']} records")
        except Exception as e:
            self._phase("failed", f"{type(e).__name__}: {e}"[:300])

    def join_script(self):
        if self.mode != "archil":
            raise RuntimeError("joining your own machine needs an Archil run")
        b = self.backend
        d = b.disk
        vals = {"__RUN__": (self.run or {}).get("id", "current"), "__DISK_ID__": d.id, "__DISK_NAME__": d.name,
                "__ORG__": d.organization, "__REGION__": d.region, "__TOKEN__": b.s.get("mount_token") or "",
                "__OPENAI__": config.OPENAI_KEY, "__KEENABLE__": config.KEENABLE_KEY,
                "__DELAY__": str(config.STEP_DELAY)}
        out = JOIN_SH
        for k, v in vals.items():
            v = str(v)
            if any(c in v for c in '"$`\\\n'):  # values sit inside double quotes in a shell script
                raise RuntimeError(f"unsafe characters in {k.strip('_').lower()}")
            out = out.replace(k, v)
        return out

    def _release(self):
        """Run finished: workers have exited on their own; stop and delete the idle sandboxes so they
        stop costing money. Results are safe on the disk."""
        time.sleep(35)  # let workers notice the run is done and exit cleanly (max idle 30s)
        try:
            n = len(self.backend.s.get("sandboxes", {}))
            self.backend.teardown()
            if self.backend.s.get("reaper"):
                try:
                    sb = self.backend.archil.get_sandbox(self.backend.s["reaper"])
                    sb.stop(); sb.delete()
                except Exception:
                    pass
            self.run.update(message=f"{self._snap['done'] if self._snap else ''} records verified; "
                                    f"{n} sandboxes released")
            self._save_run()
        except Exception as e:
            print("release failed", e, flush=True)

    def kill(self, machine, fraction):
        ws = [w for w in self.view.state()["workers"] if w["alive"] and not w["worker"].startswith("reaper")]
        if machine:
            ws = [w for w in ws if w["machine"] == machine or w["machine"].startswith(machine)]
        ws.sort(key=lambda w: w.get("tid") is None)  # prefer killing workers mid-task
        victims = ws[:max(1, int(len(ws) * fraction))] if ws else []
        return self.backend.kill([{"worker": w["worker"], "pid": w.get("pid")} for w in victims])

    def launch(self, machine, n):
        return [w["worker"] for w in self.backend.launch(n, machine)]


def make_handler(app):
    class H(BaseHTTPRequestHandler):
        def log_message(self, *a):
            pass

        def _send(self, code, body, ctype="application/json"):
            data = body if isinstance(body, bytes) else json.dumps(body).encode()
            self.send_response(code)
            self.send_header("Content-Type", ctype)
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            self.wfile.write(data)

        def do_GET(self):
            if self.path.split("?")[0] == "/header.js":
                with open(os.path.join(HERE, "header.js"), "rb") as f:
                    return self._send(200, f.read(), "application/javascript; charset=utf-8")
            page = PAGES.get(self.path.split("?")[0])
            if page:
                try:
                    with open(os.path.join(HERE, page), "rb") as f:
                        return self._send(200, f.read(), "text/html; charset=utf-8")
                except FileNotFoundError:
                    return self._send(404, {"error": f"{page} not built yet"})
            if self.path.startswith("/join.sh"):
                from urllib.parse import parse_qs, urlparse
                if parse_qs(urlparse(self.path).query).get("code", [""])[0] != JOIN_CODE:
                    return self._send(403, b"echo 'wrong or missing join code'; exit 1\n", "text/plain")
                try:
                    return self._send(200, app.join_script().encode(), "text/x-shellscript")
                except RuntimeError as e:
                    return self._send(400, f"echo '{e}'; exit 1\n".encode(), "text/plain")
            if self.path.startswith("/api/join-info"):
                return self._send(200, {"code": JOIN_CODE, "path": f"/join.sh?code={JOIN_CODE}",
                                        "available": app.mode == "archil"})
            if self.path.startswith("/api/rows"):
                from urllib.parse import parse_qs, urlparse
                qs = parse_qs(urlparse(self.path).query)
                return self._send(200, app.view.rows(changed_only=qs.get("changed", ["0"])[0] == "1",
                                                     limit=min(int(qs.get("limit", ["300"])[0]), 2000),
                                                     q=qs.get("q", [""])[0]))
            if self.path.startswith("/api/teleports"):
                return self._send(200, app.teleports())
            if self.path.startswith("/api/state"):
                return self._send(200, app.state())
            self._send(404, {"error": "not found"})

        def do_POST(self):
            body = json.loads(self.rfile.read(int(self.headers.get("Content-Length") or 0)) or b"{}")
            try:
                if self.path == "/api/start":
                    rid = app.start(str(body.get("url", "")).strip(), min(int(body.get("limit") or 200), 2000),
                                    max(1, min(int(body.get("workers") or 8), 64)))
                    return self._send(200, {"ok": True, "run_id": rid})
                if self.path == "/api/accept":
                    ids = body.get("fix_ids") or [body["fix_id"]]
                    for fid in ids:
                        app.view.accept(fid)
                    app.mark_accepted(ids)
                    return self._send(200, {"ok": True, "accepted": len(ids)})
                if self.path == "/api/kill":
                    return self._send(200, {"killed": app.kill(body.get("machine"), float(body.get("fraction", 0.5)))})
                if self.path == "/api/launch":
                    return self._send(200, {"launched": app.launch(body.get("machine") or "laptop-B",
                                                                   int(body.get("n", 3)))})
            except (ValueError, RuntimeError) as e:
                return self._send(400, {"error": str(e)})
            except Exception as e:
                return self._send(500, {"error": f"{type(e).__name__}: {e}"})
            self._send(404, {"error": "not found"})
    return H


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--archil", action="store_true")
    ap.add_argument("--port", type=int, default=8787)
    ap.add_argument("--host", default="127.0.0.1", help="0.0.0.0 lets other machines on the network join")
    a = ap.parse_args()
    app = App("archil" if a.archil else "local")
    print(f"Teleport dashboard ({app.mode}): http://localhost:{a.port}  (join code {JOIN_CODE})", flush=True)
    ThreadingHTTPServer((a.host, a.port), make_handler(app)).serve_forever()


if __name__ == "__main__":
    main()
